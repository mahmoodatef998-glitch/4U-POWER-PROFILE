-- price book links (price_list_items.model_codes)
update price_list_items p
set model_codes = (
  select array_agg(coalesce(r.new_code, u.c) order by u.o)
  from unnest(p.model_codes) with ordinality u(c, o) left join _model_rename r on r.old_code = u.c
)
where p.model_codes && (select array_agg(old_code) from _model_rename);

-- quotation lines (items[].code; the title too on drafts)
alter table quotations disable trigger quotations_touch;
update quotations q
set items = (
  select jsonb_agg(
    case when r.old_code is null then i
    else jsonb_set(i, '{code}', to_jsonb(r.new_code))
      || case when q.status = 'draft' and i->>'title' like r.old_code || ' %'
           then jsonb_build_object('title', r.new_code || substr(i->>'title', length(r.old_code) + 1)) else '{}'::jsonb end
    end order by e.o)
  from jsonb_array_elements(q.items) with ordinality e(i, o) left join _model_rename r on r.old_code = e.i->>'code'
)
where exists (select 1 from jsonb_array_elements(q.items) i join _model_rename r on r.old_code = i->>'code');
alter table quotations enable trigger quotations_touch;

-- enquiries and calculator results recorded with the old slugs
update leads l set product_slug = r.new_slug from _model_rename r where l.product_slug = r.old_slug;
update calculator_submissions c set matched_product_slug = r.new_slug from _model_rename r where c.matched_product_slug = r.old_slug;

drop table _model_rename;
